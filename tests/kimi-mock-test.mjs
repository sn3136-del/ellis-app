// Verifies the Kimi K3 integration end-to-end against a local mock of the
// Moonshot API (OpenAI-compatible /chat/completions + /models), driven through
// the LIVE app over CDP so the real IPC chain, settings routing, immigration
// system prompt, and fallback behavior are all exercised:
//   1. Kimi enabled + reachable  -> answers come from Kimi (engine: "kimi")
//   2. Kimi server goes down     -> graceful fallback to the built-in engine
//   3. Request format            -> auth header, model id, immigration-tailored system prompt
import http from 'http'

let lastRequest = null
const server = http.createServer((req, res) => {
  let body = ''
  req.on('data', (c) => { body += c })
  req.on('end', () => {
    if (req.url.endsWith('/models')) {
      res.writeHead(200, { 'content-type': 'application/json' })
      res.end(JSON.stringify({ data: [{ id: 'kimi-k3' }, { id: 'kimi-k2.6' }] }))
      return
    }
    if (req.url.endsWith('/chat/completions')) {
      const payload = JSON.parse(body || '{}')
      lastRequest = { auth: req.headers.authorization, model: payload.model, system: payload.messages?.[0]?.content || '', user: payload.messages?.at(-1)?.content || '' }
      res.writeHead(200, { 'content-type': 'application/json' })
      res.end(JSON.stringify({ choices: [{ message: { content: `MOCK-KIMI-K3: grounded immigration answer for: ${lastRequest.user.slice(0, 60)}` } }] }))
      return
    }
    res.writeHead(404); res.end('{}')
  })
})
await new Promise((r) => server.listen(8899, '127.0.0.1', r))

const list = await (await fetch('http://127.0.0.1:9222/json')).json()
const ws = new WebSocket(list.find((t) => t.type === 'page').webSocketDebuggerUrl)
await new Promise((res, rej) => { ws.onopen = res; ws.onerror = rej })
let id = 0
const pending = new Map()
ws.onmessage = (e) => { const m = JSON.parse(e.data); if (m.id && pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id) } }
const send = (method, params) => new Promise((res) => { const i = ++id; pending.set(i, res); ws.send(JSON.stringify({ id: i, method, params })) })
async function evaljs(expr) {
  const r = await send('Runtime.evaluate', { expression: expr, awaitPromise: true, returnByValue: true })
  if (r.result?.exceptionDetails) throw new Error(JSON.stringify(r.result.exceptionDetails))
  return r.result?.result?.value
}

let pass = 0, fail = 0
const ok = (c, n, x = '') => { c ? pass++ : fail++; console.log(c ? '  PASS' : '  FAIL', n, c ? '' : x) }

// Save original settings, then point Kimi at the mock.
const orig = await evaljs(`window.ellis.getSettings().then(s => s.kimi)`)
await evaljs(`window.ellis.saveSettings({ kimi: { enabled: true, apiKey: 'sk-mock-test', endpoint: 'http://127.0.0.1:8899/v1', model: 'kimi-k3' } })`)

console.log('== Kimi K3 live (mock Moonshot API) ==')
const st = await evaljs(`window.ellis.ai.kimiStatus()`)
ok(st.available === true, 'kimiStatus reports available', JSON.stringify(st))
ok((st.models || []).includes('kimi-k3'), 'models list includes kimi-k3')

const chat = await evaljs(`window.ellis.ai.assistantChat({ message: 'What documents does a Chinese national need for a US B-2 visa?', history: [] })`)
ok(chat.ok && chat.engine === 'kimi', 'assistantChat routed to Kimi', JSON.stringify({ engine: chat.engine, ok: chat.ok }))
ok((chat.data?.reply || '').startsWith('MOCK-KIMI-K3'), 'reply came from Kimi API')
ok(/immigration/i.test(lastRequest?.system || ''), 'immigration-tailored system prompt sent')
ok(/tourist visa/i.test(lastRequest?.system || ''), 'tourist-visa rules included in profile')
ok(lastRequest?.auth === 'Bearer sk-mock-test', 'Bearer auth header correct')
ok(lastRequest?.model === 'kimi-k3', 'model id kimi-k3 sent')

const q = await evaljs(`window.ellis.listCases().then(cs => window.ellis.ai.answerQuestion({ question: 'When does status expire?', case: cs[0] }))`)
ok(q.ok && q.engine === 'kimi', 'case Q&A routed to Kimi', JSON.stringify({ engine: q.engine }))
ok((q.data?.citations || []).length > 0, 'citations still attached to Kimi answers')

const plan = await evaljs(`window.ellis.planTrip({ traveler: { name: 'Chen Yu', nationality: 'China', destination: 'USA', departure: '2026-11-01', return: '2026-11-20', documents: ['passport.pdf'] } })`)
ok(plan.ok && plan.data.engine === 'kimi', 'trip plan brief generated by Kimi', JSON.stringify({ engine: plan.data?.engine }))
ok((plan.data?.brief || '').startsWith('MOCK-KIMI-K3'), 'trip brief text from Kimi')
ok(plan.data.kind === 'embassy', 'hard case China->USA still classified embassy (structured plan is deterministic)')

console.log('== Fallback when Kimi API is unreachable ==')
await new Promise((r) => server.close(r))
const chat2 = await evaljs(`window.ellis.ai.assistantChat({ message: 'What is an H-1B?', history: [] })`)
ok(chat2.ok === true, 'chat still succeeds with Kimi down')
ok(chat2.engine !== 'kimi', 'fell back off Kimi', chat2.engine)
const plan2 = await evaljs(`window.ellis.planTrip({ traveler: { name: 'A', nationality: 'India', destination: 'Japan' } })`)
ok(plan2.ok && plan2.data.engine === 'builtin' && plan2.data.kind === 'evisa', 'trip plan still complete with Kimi down')

// Restore original settings.
await evaljs(`window.ellis.saveSettings({ kimi: ${JSON.stringify(orig)} })`)

console.log(`\n${pass} passed, ${fail} failed`)
process.exit(fail ? 1 : 0)
